// -----------------------------------------------------------------------------
// Функція формування матриці випадковими числами
// -----------------------------------------------------------------------------
void Create(int** a, const int rowCount, const int colCount, const int Low, const int High)
{
    // Проходимо по всіх рядках матриці від 0 до rowCount - 1
    for (int i = 0; i < rowCount; i++)
    {
        // У кожному рядку проходимо по всіх стовпчиках від 0 до colCount - 1
        for (int j = 0; j < colCount; j++)
        {
            // Генеруємо випадкове число у діапазоні [Low, High]
            // Формула: Low + rand() % (High - Low + 1)
            a[i][j] = Low + rand() % (High - Low + 1);
        }
    }
}

// -----------------------------------------------------------------------------
// Функція виведення матриці у вигляді таблиці з фіксованою шириною колонок
// -----------------------------------------------------------------------------
void Print(int** a, const int rowCount, const int colCount)
{
    cout << endl; // порожній рядок перед таблицею
    for (int i = 0; i < rowCount; i++)
    {
        for (int j = 0; j < colCount; j++)
        {
            // setw(5) виділяє 5 позицій під кожне число для красивого вирівнювання
            cout << setw(5) << a[i][j];
        }
        cout << endl; // перехід на новий рядок після виведення всіх стовпчиків
    }
    cout << endl; // порожній рядок після таблиці
}

// -----------------------------------------------------------------------------
// Функція обміну елементів двох рядків матриці (row1 та row2)
// -----------------------------------------------------------------------------
void Change(int** a, const int row1, const int row2, const int colCount)
{
    int tmp; // проміжна змінна для збереження значення під час обміну
    for (int j = 0; j < colCount; j++)
    {
        tmp = a[row1][j];          // запам'ятовуємо елемент першого рядка
        a[row1][j] = a[row2][j];  // записуємо в перший рядок елемент з другого
        a[row2][j] = tmp;          // у другий рядок записуємо збережене значення
    }
}

// -----------------------------------------------------------------------------
// Функція сортування рядків матриці за трьома ключами (метод «бульбашки»)
// Ключі варіанта 16: ↓ ↓ ↓
// 1) 1-й стовпчик (індекс 0) — за спаданням;
// 2) при рівності — 2-й стовпчик (індекс 1) — за спаданням;
// 3) при рівності — 3-й стовпчик (індекс 2) — за спаданням.
// -----------------------------------------------------------------------------
void Sort(int** a, const int rowCount, const int colCount)
{
    // Зовнішній цикл: кількість проходів сортування
    for (int i0 = 0; i0 < rowCount - 1; i0++)
    {
        // Внутрішній цикл: попарне порівняння сусідніх рядків i1 та i1 + 1
        for (int i1 = 0; i1 < rowCount - i0 - 1; i1++)
        {
            // Перевіряємо умову потреби перестановки для спадання:
            // Рядок i1 повинен іти ПЕРЕД рядком i1 + 1.
            // Якщо для спадання верхній менший за нижній — їх треба міняти!
            if ((a[i1][0] < a[i1 + 1][0]) // 1-й ключ: 1-й стовпчик за спаданням
                ||
                (a[i1][0] == a[i1 + 1][0] && // якщо в 1-му стовпчику рівні
                 a[i1][1] < a[i1 + 1][1])    // 2-й ключ: 2-й стовпчик за спаданням
                ||
                (a[i1][0] == a[i1 + 1][0] && // якщо в 1-му і 2-му стовпчиках рівні
                 a[i1][1] == a[i1 + 1][1] &&
                 a[i1][2] < a[i1 + 1][2]))   // 3-й ключ: 3-й стовпчик за спаданням
            {
                // Міняємо ці два рядки місцями
                Change(a, i1, i1 + 1, colCount);
            }
        }
    }
}

// -----------------------------------------------------------------------------
// Функція обчислення суми S, кількості k та заміни нулями
// Критерій Варіанта 16: «всі, крім: парних кратних 13»
// -----------------------------------------------------------------------------
void Calc(int** a, const int rowCount, const int colCount, int& S, int& k)
{
    S = 0; // обнуляємо суму перед початком підрахунку
    k = 0; // обнуляємо лічильник кількості

    for (int i = 0; i < rowCount; i++)
    {
        for (int j = 0; j < colCount; j++)
        {
            // «Парні кратні 13» означає: (a[i][j] % 2 == 0 && a[i][j] % 13 == 0)
            // «Всі, крім...» означає заперечення цієї умови: ! (...)
            if (!(a[i][j] % 2 == 0 && a[i][j] % 13 == 0))
            {
                S += a[i][j]; // додаємо елемент до суми
                k++;          // збільшуємо лічильник кількості
                a[i][j] = 0;  // замінюємо опрацьований елемент нулем за вимогою
            }
        }
    }
}

